//! Прибор инвертированного RED-гейта: тест, который падает всегда.
//!
//! Это не забытая работа, а измерительный прибор. Он лежит в дереве всегда и
//! падает всегда; общий прогон его не видит, потому что таргет закрыт
//! признаком `red-fixture` (ADR-0004).
//!
//! Существует он потому, что «принимает красное» иначе нечем доказать: до
//! F-31 позитивная фикстура одалживала чужой красный бинарь и протухала ровно
//! в момент слияния (F-26, затем F-31 на `session_failure`).

/// Падает честным `assert`, а не `#[ignore]` и не `#[should_panic]`.
/// Гейт классифицирует код возврата, поэтому прибор обязан дать тот самый 101,
/// который уже распознаётся, — иначе он сертифицировал бы произвольную ошибку.
#[test]
fn red_fixture_is_red_by_construction() {
    assert!(
        false,
        "это прибор, а не забытая работа: инвертированный RED-гейт обязан видеть \
         падение, которого нельзя случайно позеленеть. Общий прогон этот таргет не \
         собирает — он включается только признаком `red-fixture`."
    );
}
